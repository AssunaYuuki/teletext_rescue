# tu-tx100-mosaics.json (JTES Decoder 0.9.55, mosaics captured from a Panasonic TU-TX100) -> src/jtes_mosaic.inc
# usage: python mosaic2inc.py <tu-tx100-mosaics.json> <out .inc>
import json, sys

d = json.load(open(sys.argv[1], encoding='utf-8'))
sets = ['A', 'B', 'C', 'D', 'DS']
out = ['// Mosaic sets A-D of Japanese teletext as the Panasonic TU-TX100 draws them (captured from its video output',
       '// by JTES Decoder 0.9.55, assets/tu-tx100-mosaics.json): 94 codes 21..7E per set, 16 x 24 dots, rows top down,',
       '// MSB = left dot. Sets: A, B, C, D, DS (= D under STL). Codes the receiver leaves blank (reserved) have',
       '// jtMosaicHas = 0. Generated by tools/jtes/mosaic2inc.py.',
       'static const uint16_t jtMosaic[5 * 94][24] = {']
has = []
for s in sets:
    t = d[s]
    for c in range(0x21, 0x7F):
        h = t.get('%02X' % c)
        has.append(1 if h else 0)
        rows = [int(h[i * 4:i * 4 + 4], 16) for i in range(24)] if h else [0] * 24
        out.append('    {' + ','.join('0x%04X' % r for r in rows) + '},')
out.append('};')
out.append('static const uint8_t jtMosaicHas[5 * 94] = {')
for i in range(0, len(has), 47):
    out.append('    ' + ','.join(map(str, has[i:i + 47])) + ',')
out.append('};')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(sum(has), 'rasters')
