# Writes src/jtes_fonts.inc from the Panasonic TU-TX100 teletext tuner fonts (BDF, indexed by JIS X 0208 code):
#   tu-tx100.bdf 16x24 full width, tu-tx100-halfwidth.bdf 8x24, tu-tx100-small.bdf 8x12.
# usage: bdf2inc.py <folder with the .bdf files> <out.inc>
import os, sys

def read_bdf(path):
    glyphs = {}
    code, rows, inbm = None, [], False
    for line in open(path, encoding='latin-1'):
        t = line.split()
        if not t: continue
        if t[0] == 'ENCODING': code = int(t[1])
        elif t[0] == 'BITMAP': rows, inbm = [], True
        elif t[0] == 'ENDCHAR':
            if code is not None: glyphs[code] = rows
            code, inbm = None, False
        elif inbm: rows.append(int(t[0], 16))
    return glyphs

src, out = sys.argv[1], sys.argv[2]
fonts = [('jtFull', 'tu-tx100.bdf', 24, 2), ('jtHalf', 'tu-tx100-halfwidth.bdf', 24, 1), ('jtSmall', 'tu-tx100-small.bdf', 12, 1)]
w = open(out, 'w', newline='\n')
w.write('// Generated by tools/jtes/bdf2inc.py from the Panasonic TU-TX100 teletext tuner fonts (JP/*.bdf). Do not edit.\n')
w.write('// Glyphs sorted by JIS X 0208 code; rows top to bottom, bit 7 of the first byte = leftmost dot.\n\n')
for name, fn, h, bpr in fonts:
    g = read_bdf(os.path.join(src, fn))
    codes = sorted(g)
    w.write('static const int %sCount = %d, %sHeight = %d, %sWidth = %d;\n' % (name, len(codes), name, h, name, 8 * bpr))
    w.write('static const uint16_t %sCode[%d] = {\n' % (name, len(codes)))
    for i in range(0, len(codes), 16):
        w.write('    ' + ', '.join('0x%04X' % c for c in codes[i:i + 16]) + ',\n')
    w.write('};\n')
    w.write('static const uint8_t %sBits[%d][%d] = {\n' % (name, len(codes), h * bpr))
    for c in codes:
        rows = (g[c] + [0] * h)[:h]
        bs = []
        for r in rows:
            for k in range(bpr - 1, -1, -1): bs.append((r >> (8 * k)) & 0xFF)
        w.write('    {' + ','.join(str(b) for b in bs) + '},\n')
    w.write('};\n\n')
# JIS X 0208 -> Unicode for the text output: index (row - 1) * 94 + (cell - 1), 0 = no character
uni = []
for r in range(1, 95):
    for c in range(1, 95):
        try: ch = bytes([0xA0 + r, 0xA0 + c]).decode('euc_jp'); uni.append(ord(ch) if len(ch) == 1 else 0)
        except UnicodeDecodeError: uni.append(0)
w.write('// JIS X 0208 row/cell -> Unicode, index (row - 1) * 94 + cell - 1\n')
w.write('static const uint16_t jtJisUni[%d] = {\n' % len(uni))
for i in range(0, len(uni), 16):
    w.write('    ' + ', '.join('0x%04X' % u for u in uni[i:i + 16]) + ',\n')
w.write('};\n')
w.close()
print('wrote', out)
