# Writes src/gemstar_tables.inc: the tables FREQCCD_.EXE (Gemstar VBI Data Monitor 1.5) uses to
# descramble / decrypt / decompress Gemstar data, plus DDPACKET.BIN and the monthly *.INP keys.
# usage: geninc.py <folder with FREQCCD_.EXE, DDPACKET.BIN, *.INP> <out.inc>
import sys, os, glob, struct

src, out = sys.argv[1], sys.argv[2]
d = open(os.path.join(src, 'FREQCCD_.EXE'), 'rb').read()
ds = struct.unpack_from('<H', d, 8)[0] * 16 + (0x33cf - 0x1000) * 16
seg = lambda off, n: d[ds + off: ds + off + n]

def arr(name, data, ctype='uint8_t', per=24):
    s = 'static const %s %s[%d] = {\n' % (ctype, name, len(data))
    for i in range(0, len(data), per):
        s += '    ' + ', '.join(str(x) for x in data[i:i + per]) + ',\n'
    return s + '};\n'

w = open(out, 'w', newline='\n')
w.write('// Generated by tools/gemstar/geninc.py from the Gemstar VBI Data Monitor 1.5 floppy\n'
        '// (FREQCCD_.EXE data segment, DDPACKET.BIN, <month*100+year%100>.INP). Do not edit.\n\n')
w.write('// DS:111E "INDEX SYSTEM,INC" + substitution table (Type A descramble, Type B key schedule)\n')
w.write(arr('gsSub', seg(0x111e, 0x100)))
w.write('// DS:2882 / DS:2982 byte permutations (Type B cipher)\n')
w.write(arr('gsP0', seg(0x2882, 0x100)))
w.write(arr('gsP1', seg(0x2982, 0x100)))
w.write('// DS:4080..47FF text decompression tables (index = DS offset - 0x4080)\n')
w.write('static const int gsTxtBase = 0x4080;\n')
w.write(arr('gsTxt', seg(0x4080, 0x780)))
w.write('// DDPACKET.BIN, the dynamic dictionary\n')
w.write(arr('gsDict', open(os.path.join(src, 'DDPACKET.BIN'), 'rb').read()))
w.write('// DS:3D82 / DS:3F02 PlusCode tables\n')
w.write(arr('gsPcU', struct.unpack_from('<192H', d, ds + 0x3d82), 'uint16_t', 16))
w.write(arr('gsPcW', struct.unpack_from('<31H', d, ds + 0x3f02), 'uint16_t', 16))
keys = []
for f in glob.glob(os.path.join(src, '*.INP')):
    v = int(os.path.basename(f)[:-4])
    keys.append((v % 100, v // 100, [int(x) for x in open(f).read().split()]))
keys.sort()
w.write('// monthly Type A keys: year % 100, month, steps (negative = also swap)\n')
w.write('struct GsKey { int year, month, n; int8_t v[80]; };\n')
w.write('static const GsKey gsKeys[] = {\n')
for y, m, v in keys:
    w.write('    {%d, %d, %d, {%s}},\n' % (y, m, len(v), ', '.join(map(str, v))))
w.write('};\n')
w.close()
print('wrote', out, len(keys), 'keys')
